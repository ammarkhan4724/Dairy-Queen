"""Generate src/pages/items/<slug>.astro from item_content/*.py on the ItemPage layout.

Each content module defines ITEMS: a list of dicts with hand-written copy plus the
item's facts. Prices, calories, the quick answer, spec table, size table and the
standard FAQs are all built from those facts so every page stays consistent.

Usage:  python build_item_pages.py            (all content files)
        python build_item_pages.py blizzards  (one content file)
"""
import importlib.util, json, os, sys, glob

ROOT = os.path.dirname(os.path.abspath(__file__))
CATS = {
    'blizzard': ('Blizzard Treats', '/categories/blizzard-treats'),
    'classic': ('Classic Treats', '/categories/classic-treats'),
    'drinks': ('Drinks', '/categories/drinks'),
    'snacks': ('Snacks & Sides', '/categories/snacks-sides'),
    'burgers': ('Burgers & Sandwiches', '/categories/burgers-sandwiches'),
    'chicken': ('Chicken Strip Baskets', '/categories/chicken-strip-baskets'),
    'breakfast': ('Breakfast', '/categories/breakfast'),
    'kids': ('Kids Meals', '/categories/kids-meals'),
    'deals': ('Deals & Combos', '/combos'),
}
SIZE_NAMES = ['Mini', 'Small', 'Medium', 'Large']


def js(v):
    return json.dumps(v, ensure_ascii=False)


def a_or_an(word):
    return 'An' if word[:1].lower() in 'aeiou' or word.startswith(('M&M', 'Oreo')) else 'A'


def build(it):
    slug, name = it['slug'], it['name']
    short = it.get('short', name)          # name used in sentences
    sizes = it.get('sizes')                # list of (label, price, cal) or None
    price = it.get('price')                # single price for one-size items
    cal = it.get('cal')
    avail = it.get('avail', '')
    note = ' Prices vary by location.'

    # Quick answer
    if sizes and [s[0] for s in sizes] == SIZE_NAMES:
        p = {s[0]: s[1] for s in sizes}
        quick = (f"{a_or_an(short)} {short} at Dairy Queen costs about {p['Mini']} for a Mini, {p['Small']} for a Small, "
                 f"{p['Medium']} for a Medium and {p['Large']} for a Large. A Small has about {sizes[1][2].lstrip('~')} calories.")
        price_faq = (f"How much is {a_or_an(short).lower()} {short}?",
                     f"It typically costs about {p['Mini']} for a Mini, {p['Small']} for a Small, {p['Medium']} for a Medium and {p['Large']} for a Large. Prices vary by location.")
        cal_faq = (f"How many calories are in {a_or_an(short).lower()} {short}?",
                   'About ' + ', '.join(f"{s[2].lstrip('~')} for a {s[0]}" for s in sizes[:-1]) + f" and {sizes[-1][2].lstrip('~')} for a {sizes[-1][0]}.")
        frm = f"From {p['Mini']}"
    elif sizes:
        quick = it['quick']
        price_faq = (it['price_q'], it['price_a'])
        cal_faq = None
        frm = f"From {sizes[0][1]}"
    else:
        art = it.get('article', 'The')
        verb = 'cost' if it.get('plural') else 'costs'
        have = 'have' if it.get('plural') else 'has'
        quick = it.get('quick') or f"{art} {short} at Dairy Queen {verb} about {price}" + (f" and {have} about {cal} calories." if cal else '.')
        price_faq = (it.get('price_q', f"How much {'are' if it.get('plural') else 'is'} the {short} at Dairy Queen?"),
                     it.get('price_a', f"{'They cost' if it.get('plural') else 'It costs'} about {price}" + (f" and {have} about {cal} calories." if cal else '.') + note))
        cal_faq = None
        frm = price
    if avail and not it.get('quick'):
        quick += ' ' + avail
    if not quick.endswith('location.'):
        quick += note

    faqs = [price_faq] + ([cal_faq] if cal_faq else []) + [tuple(f) for f in it.get('faqs', [])]
    spec = it.get('spec', [])
    table = None
    if sizes:
        table = {'title': f"{short} price and calories by size", 'head': ['Size', 'Price', 'Calories'],
                 'rows': [[s[0], s[1], s[2]] for s in sizes]}
    cat = CATS[it['cat']]

    props = [
        f"  title={js(it['title'])}",
        f"  description={js(it['desc'])}",
        f"  name={js(name)}",
        f"  category={{{{ name: {js(cat[0])}, href: {js(cat[1])} }}}}",
        f"  image={js(it['image'])}",
        f"  imageAlt={js(it['alt'])}",
        f"  badges={{{js(it.get('badges', []))}}}",
        f"  quick={js(quick)}",
        f"  from={js(frm)}",
        f"  intro={js(it['intro'])}",
        f"  spec={{{js(spec)}}}",
    ]
    if it.get('allergens'):
        props.append(f"  allergens={js(it['allergens'])}")
    if table:
        props.append(f"  table={{{js(table)}}}")
    props.append('  faqs={faqs}')

    faq_js = ',\n'.join(f"  {{ q: {js(q)}, a: {js(a)} }}" for q, a in faqs)
    out = (
        "---\n// Generated by build_item_pages.py from item_content/. Edit the content file, not this page.\n"
        "import ItemPage from '../../layouts/ItemPage.astro';\n\n"
        f"const faqs = [\n{faq_js},\n];\n---\n"
        "<ItemPage\n" + '\n'.join(props) + "\n>\n" + it['body'].strip() + "\n</ItemPage>\n"
    )
    path = os.path.join(ROOT, 'src', 'pages', 'items', f'{slug}.astro')
    with open(path, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write(out)


def load(path):
    spec = importlib.util.spec_from_file_location(os.path.basename(path)[:-3], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.ITEMS


if __name__ == '__main__':
    names = sys.argv[1:]
    files = sorted(glob.glob(os.path.join(ROOT, 'item_content', '*.py')))
    if names:
        files = [f for f in files if os.path.basename(f)[:-3] in names]
    n = 0
    for f in files:
        for it in load(f):
            build(it)
            n += 1
    print(f'Generated {n} item pages')
